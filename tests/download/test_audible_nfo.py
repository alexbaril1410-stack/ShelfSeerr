from pathlib import Path

from shelfmark.core.models import DownloadTask
from shelfmark.download.postprocess.transfer import (
    _write_audible_nfo_file,
    build_audible_nfo_content,
)


def _audible_task(**overrides):
    values = {
        "task_id": "audible-release",
        "source": "prowlarr",
        "title": "Le livre des étoiles",
        "author": "Erik L'Homme",
        "year": "2024",
        "content_type": "audiobook",
        "metadata_provider": "audible",
        "metadata_provider_id": "B08BKGYQXW",
        "metadata_description": "Une aventure\nfantastique.",
        "metadata_publisher": "Gallimard Audio",
        "metadata_genres": ["Fantasy", "Jeunesse"],
        "metadata_language": "fr",
        "metadata_authors": ["Erik L'Homme"],
        "metadata_narrators": ["Benjamin Jungers"],
        "series_name": "Le Livre des étoiles",
        "series_position": 1,
    }
    values.update(overrides)
    return DownloadTask(**values)


def test_build_audible_nfo_uses_audiobookshelf_supported_fields():
    content = build_audible_nfo_content(_audible_task())

    assert content is not None
    assert "Title: Le livre des étoiles" in content
    assert "Author: Erik L'Homme" in content
    assert "Narrator: Benjamin Jungers" in content
    assert "Series Name: Le Livre des étoiles" in content
    assert "Position in Series: 1" in content
    assert "ASIN: B08BKGYQXW" in content
    assert "Publisher: Gallimard Audio" in content
    assert "Genre: Fantasy, Jeunesse" in content
    assert "Language: fr" in content
    assert "Une aventure fantastique." in content


def test_build_audible_nfo_only_runs_for_audible_audiobooks():
    assert build_audible_nfo_content(_audible_task(metadata_provider="hardcover")) is None
    assert build_audible_nfo_content(_audible_task(content_type="ebook")) is None
    assert build_audible_nfo_content(_audible_task(metadata_provider_id=None)) is None


def test_write_audible_nfo_preserves_existing_release_nfo(tmp_path: Path):
    release_nfo = tmp_path / "release.nfo"
    release_nfo.write_text("Title: Release supplied metadata", encoding="utf-8")

    written = _write_audible_nfo_file(tmp_path, "Title: Audible metadata\\n")

    assert written is False
    assert release_nfo.read_text(encoding="utf-8") == "Title: Release supplied metadata"
    assert not (tmp_path / "metadata.nfo").exists()


def test_write_audible_nfo_updates_its_own_generated_file(tmp_path: Path):
    first = "# Generated by ShelfSeerr - Audible metadata\\nTitle: First\\n"
    second = "# Generated by ShelfSeerr - Audible metadata\\nTitle: Updated\\n"

    assert _write_audible_nfo_file(tmp_path, first) is True
    assert _write_audible_nfo_file(tmp_path, second) is True
    assert (tmp_path / "metadata.nfo").read_text(encoding="utf-8") == second
